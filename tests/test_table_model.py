def test_options_an_engine_does_not_have_are_dropped_not_rendered():
    model = _optioned(ENGINE="InnoDB", **{"WITHOUT ROWID": "true"})
    # SQLite has no ENGINE and MySQL has no WITHOUT ROWID: each renders
    # only its own, and the model survives the trip either way.
    assert render_create(model, SQLITE).endswith(") WITHOUT ROWID")
    assert render_create(model, MYSQL).endswith(") ENGINE=InnoDB")
    pruned = prune_options(model, MYSQL)
    assert pruned.options == {"ENGINE": "InnoDB"}
    assert prune_options(model, SQLITE).options == {"WITHOUT ROWID": "true"}


def test_options_round_trip_through_json():
    model = TableModel(
        name="t",
        columns=(
            ColumnModel("id", "INT", identity=True, options={"x": "1"}),
        ),
        options={"ENGINE": "InnoDB", "AUTO_INCREMENT": "7"},
    )
    back = load_state(dump_state(model))
    assert back is not None
    assert back.options == model.options
    assert back.columns[0].options == {"x": "1"}
    assert back.columns[0].identity is True
    assert to_dict(from_dict(to_dict(model))) == to_dict(model)


def test_changing_an_alterable_option_plans_an_alter():
    before = _optioned(ENGINE="MyISAM")
    after = _optioned(ENGINE="InnoDB", ROW_FORMAT="DYNAMIC")
    statements = plan(before, after, MYSQL)
    assert [s.sql for s in statements] == [
        "ALTER TABLE `t` ENGINE=InnoDB",
        "ALTER TABLE `t` ROW_FORMAT=DYNAMIC",
    ]
    assert {s.classification for s in statements} == {"rewrite"}
    # A storage parameter is set and reset rather than rewritten.
    assert [s.sql for s in plan(_optioned(fillfactor="80"), _optioned(),
                               POSTGRES)] == [
        'ALTER TABLE "t" RESET (fillfactor)'
    ]
    assert [s.sql for s in plan(_optioned(), _optioned(fillfactor="80"),
                                POSTGRES)] == [
        'ALTER TABLE "t" SET (fillfactor = 80)'
    ]


def test_an_option_the_engine_cannot_alter_plans_nothing():
    # SQLite's WITHOUT ROWID is not alterable, so a model that gained
    # it plans no statement rather than SQL SQLite would refuse.
    assert plan(_optioned(), _optioned(**{"WITHOUT ROWID": "true"}),
                SQLITE) == []
