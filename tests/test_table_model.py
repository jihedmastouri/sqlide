def _optioned(**options) -> TableModel:
    return TableModel(
        name="t",
        columns=(ColumnModel("id", "INT", nullable=False, primary_key=True),),
        options=options,
    )


def test_mysql_table_options_render_in_the_engines_own_syntax():
    sql = render_create(
        _optioned(
            ENGINE="InnoDB",
            **{"DEFAULT CHARSET": "utf8mb4"},
            COLLATE="utf8mb4_unicode_ci",
            AUTO_INCREMENT="100",
            ROW_FORMAT="DYNAMIC",
        ),
        MYSQL,
    )
    tail = sql.split(")")[-1]
    # Declared order, which is the order the grammar wants.
