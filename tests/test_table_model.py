# Rendering


def test_render_create_sqlite():
    assert render_create(_people(), SQLITE) == (
        'CREATE TABLE "people" (\n'
        '  "id" INTEGER NOT NULL,\n'
        '  "name" TEXT NOT NULL,\n'
        "  \"bio\" TEXT DEFAULT 'hello',\n"
        '  PRIMARY KEY ("id")\n'
        ")"
    )


def test_render_create_quotes_per_dialect():
    sql = render_create(_people(), MYSQL)
    assert "`people`" in sql and '`id` INTEGER NOT NULL' in sql
    assert '"' not in sql


